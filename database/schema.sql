-- ============================================================
-- CIMSE - Esquema PostgreSQL 16
-- Convertido desde el script Oracle "base_datos_seguridad.txt"
-- (NUMBER->INTEGER/NUMERIC, VARCHAR2->VARCHAR, SYSDATE->CURRENT_DATE,
--  BLOB->BYTEA, y los ALTER TABLE de la ampliacion ya integrados en cada CREATE TABLE)
-- ============================================================
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------- 1. CATALOGOS ----------
CREATE TABLE turnos (
    id_turno INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL,
    hora_inicio VARCHAR(5) NOT NULL,
    hora_fin VARCHAR(5) NOT NULL,
    CONSTRAINT chk_turno_nombre CHECK (nombre IN ('MATUTINO', 'VESPERTINO', 'NOCTURNO'))
);

CREATE TABLE clientes (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    rtn VARCHAR(20) UNIQUE,
    direccion VARCHAR(200),
    telefono VARCHAR(20),
    correo VARCHAR(100),
    contacto VARCHAR(100),
    fecha_registro DATE DEFAULT CURRENT_DATE
);

CREATE TABLE proveedores (
    id_proveedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_proveedor VARCHAR(100),
    nombre VARCHAR(100) NOT NULL,
    rtn VARCHAR(20) UNIQUE,
    telefono VARCHAR(20),
    direccion VARCHAR(200),
    correo VARCHAR(100),
    contacto VARCHAR(100)
);

CREATE TABLE permisos_administrativos (
    id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(50) NOT NULL,
    numero_permiso VARCHAR(50),
    fecha_emision DATE,
    fecha_vencimiento DATE NOT NULL,
    estado VARCHAR(20) DEFAULT 'VIGENTE' CHECK (estado IN ('VIGENTE', 'VENCIDO'))
);

-- ---------- 2. RECURSOS HUMANOS ----------
CREATE TABLE empleados (
    id_empleado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identidad VARCHAR(15) NOT NULL UNIQUE,
    nombre_completo VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE,
    direccion VARCHAR(200),
    telefono VARCHAR(20),
    correo VARCHAR(100),
    cargo VARCHAR(30) CHECK (cargo IN ('GUARDIA', 'SUPERVISOR', 'GERENTE_OPERACIONES', 'ADMINISTRATIVO', 'GERENTE_GENERAL')),
    estado_candidato VARCHAR(20) DEFAULT 'APROBADO' CHECK (estado_candidato IN ('APROBADO', 'RECHAZADO', 'CONTRATADO')),
    sueldo_base NUMERIC(10,2),
    fecha_ingreso DATE DEFAULT CURRENT_DATE,
    fecha_retiro DATE,
    activo CHAR(1) DEFAULT 'S' CHECK (activo IN ('S', 'N'))
);

CREATE TABLE usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INTEGER NOT NULL,
    nombre_usuario VARCHAR(50) NOT NULL UNIQUE,
    contrasena_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(30) NOT NULL CHECK (rol IN ('GERENTE_GENERAL', 'GERENTE_OPERACIONES', 'ADMINISTRADOR', 'SUPERVISOR', 'GUARDIA')),
    activo CHAR(1) DEFAULT 'S' CHECK (activo IN ('S', 'N')),
    ultimo_acceso TIMESTAMP,
    CONSTRAINT fk_usu_emp FOREIGN KEY (id_empleado) REFERENCES empleados(id_empleado)
);

CREATE TABLE solicitudes (
    id_solicitud INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INTEGER NOT NULL,
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('VACACIONES', 'PERMISO', 'CAMBIO_TURNO')),
    fecha_solicitud DATE DEFAULT CURRENT_DATE,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    motivo VARCHAR(200),
    estado VARCHAR(20) DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA')),
    id_aprobador INTEGER,
    comentarios_aprobador VARCHAR(200),
    CONSTRAINT fk_sol_emp FOREIGN KEY (id_empleado) REFERENCES empleados(id_empleado),
    CONSTRAINT fk_sol_aprob FOREIGN KEY (id_aprobador) REFERENCES empleados(id_empleado)
);

CREATE TABLE documentos_empleados (
    id_documento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INTEGER NOT NULL,
    tipo_documento VARCHAR(50) NOT NULL,
    nombre_archivo VARCHAR(200),
    archivo_blob BYTEA,
    fecha_subida DATE DEFAULT CURRENT_DATE,
    observaciones VARCHAR(200),
    CONSTRAINT fk_doc_emp FOREIGN KEY (id_empleado) REFERENCES empleados(id_empleado)
);

-- ---------- 3. OPERACIONES ----------
CREATE TABLE puestos_trabajo (
    id_puesto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL,
    descripcion VARCHAR(100) NOT NULL,
    ubicacion VARCHAR(200),
    tipo_turno VARCHAR(10) CHECK (tipo_turno IN ('12h', '24h')),
    horas_contratadas SMALLINT,
    estado VARCHAR(20) DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT fk_pue_cli FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente)
);

CREATE TABLE contratos (
    id_contrato INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_vencimiento DATE NOT NULL,
    duracion_anios SMALLINT CHECK (duracion_anios IN (1, 2)),
    monto_mensual NUMERIC(10,2) NOT NULL,
    dia_pago_estipulado SMALLINT CHECK (dia_pago_estipulado IN (15, 30)),
    cai_factura VARCHAR(50),
    estado VARCHAR(20) DEFAULT 'VIGENTE' CHECK (estado IN ('VIGENTE', 'VENCIDO', 'RENOVADO')),
    observaciones VARCHAR(200),
    CONSTRAINT fk_con_cli FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente)
);

CREATE TABLE facturas_emitidas (
    id_factura INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_contrato INTEGER NOT NULL,
    numero_factura VARCHAR(50) NOT NULL,
    fecha_emision DATE NOT NULL,
    monto NUMERIC(10,2) NOT NULL,
    fecha_pago DATE,
    estado_pago VARCHAR(20) DEFAULT 'PENDIENTE' CHECK (estado_pago IN ('PENDIENTE', 'PAGADO')),
    CONSTRAINT fk_fac_con FOREIGN KEY (id_contrato) REFERENCES contratos(id_contrato)
);

CREATE TABLE asignacion_puestos (
    id_asignacion_puesto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INTEGER NOT NULL,
    id_puesto INTEGER NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    turno_real VARCHAR(20),
    observaciones VARCHAR(200),
    id_turno INTEGER,
    estado_asignacion VARCHAR(20) DEFAULT 'ACTIVA',
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    id_usuario_asigna INTEGER,
    CONSTRAINT fk_asp_emp FOREIGN KEY (id_empleado) REFERENCES empleados(id_empleado),
    CONSTRAINT fk_asp_pue FOREIGN KEY (id_puesto) REFERENCES puestos_trabajo(id_puesto),
    CONSTRAINT fk_asp_turno FOREIGN KEY (id_turno) REFERENCES turnos(id_turno),
    CONSTRAINT fk_asp_usuario FOREIGN KEY (id_usuario_asigna) REFERENCES usuarios(id_usuario),
    CONSTRAINT chk_asp_estado CHECK (estado_asignacion IN ('ACTIVA', 'FINALIZADA', 'CANCELADA')),
    CONSTRAINT chk_asp_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    -- un guardia no puede tener dos asignaciones ACTIVAS que se traslapen en fechas en el mismo turno
    CONSTRAINT ex_asp_sin_traslape EXCLUDE USING gist (
        id_empleado WITH =,
        id_turno WITH =,
        (daterange(fecha_inicio, COALESCE(fecha_fin, 'infinity'::date), '[]')) WITH &&
    ) WHERE (estado_asignacion = 'ACTIVA')
);

CREATE TABLE asistencia_diaria (
    id_asistencia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INTEGER NOT NULL,
    id_asignacion_puesto INTEGER NOT NULL,
    fecha DATE NOT NULL,
    hora_entrada TIMESTAMP,
    hora_salida TIMESTAMP,
    id_turno INTEGER,
    estado_asistencia VARCHAR(20) DEFAULT 'PENDIENTE' CHECK (estado_asistencia IN ('PENDIENTE', 'PRESENTE', 'AUSENTE', 'JUSTIFICADO')),
    entrega_realizada CHAR(1) DEFAULT 'N' CHECK (entrega_realizada IN ('S', 'N')),
    recepcion_realizada CHAR(1) DEFAULT 'N' CHECK (recepcion_realizada IN ('S', 'N')),
    observaciones VARCHAR(200),
    CONSTRAINT fk_asi_emp FOREIGN KEY (id_empleado) REFERENCES empleados(id_empleado),
    CONSTRAINT fk_asi_asp FOREIGN KEY (id_asignacion_puesto) REFERENCES asignacion_puestos(id_asignacion_puesto),
    CONSTRAINT fk_asi_turn FOREIGN KEY (id_turno) REFERENCES turnos(id_turno)
);

CREATE TABLE supervision_operativa (
    id_supervision INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INTEGER NOT NULL,
    id_asistencia INTEGER NOT NULL,
    fecha_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    guardia_presente CHAR(1) DEFAULT 'S' CHECK (guardia_presente IN ('S', 'N')),
    incidencia_detectada VARCHAR(500),
    firma_libro CHAR(1) DEFAULT 'S' CHECK (firma_libro IN ('S', 'N')),
    observaciones VARCHAR(200),
    id_empleado_reemplazo INTEGER,
    CONSTRAINT fk_sup_emp FOREIGN KEY (id_empleado) REFERENCES empleados(id_empleado),
    CONSTRAINT fk_sup_asi FOREIGN KEY (id_asistencia) REFERENCES asistencia_diaria(id_asistencia),
    CONSTRAINT fk_sup_reemp FOREIGN KEY (id_empleado_reemplazo) REFERENCES empleados(id_empleado)
);

CREATE TABLE incidencias (
    id_incidencia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado_reporte INTEGER NOT NULL,
    id_puesto INTEGER,
    id_supervisor_asignado INTEGER,
    fecha_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('AUSENCIA', 'LLEGADA_TARDIA', 'PROBLEMA_CLIENTE', 'INCIDENTE_SEGURIDAD', 'OTRO')),
    descripcion VARCHAR(500) NOT NULL,
    estado VARCHAR(20) DEFAULT 'ABIERTA' CHECK (estado IN ('ABIERTA', 'EN_PROCESO', 'RESUELTA')),
    CONSTRAINT fk_inc_rep FOREIGN KEY (id_empleado_reporte) REFERENCES empleados(id_empleado),
    CONSTRAINT fk_inc_pue FOREIGN KEY (id_puesto) REFERENCES puestos_trabajo(id_puesto),
    CONSTRAINT fk_inc_sup FOREIGN KEY (id_supervisor_asignado) REFERENCES empleados(id_empleado)
);

-- ---------- 4. COMPRAS, INVENTARIO, ACTIVOS ----------
CREATE TABLE compras_proveedores (
    id_compra INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proveedor INTEGER NOT NULL,
    id_empleado_autoriza INTEGER,
    categoria_insumo VARCHAR(50) CHECK (categoria_insumo IN ('UNIFORMES', 'ARMAS', 'VEHICULOS', 'PAPELERIA', 'MATERIALES')),
    numero_factura VARCHAR(50) NOT NULL,
    monto_total NUMERIC(10,2) NOT NULL,
    fecha_compra DATE DEFAULT CURRENT_DATE,
    estado_pago VARCHAR(20) DEFAULT 'PENDIENTE' CHECK (estado_pago IN ('PENDIENTE', 'PAGADO')),
    observaciones VARCHAR(200),
    CONSTRAINT fk_com_prov FOREIGN KEY (id_proveedor) REFERENCES proveedores(id_proveedor),
    CONSTRAINT fk_com_emp FOREIGN KEY (id_empleado_autoriza) REFERENCES empleados(id_empleado)
);

CREATE TABLE detalle_compras (
    id_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra INTEGER NOT NULL,
    descripcion VARCHAR(200) NOT NULL,
    cantidad NUMERIC(10,2) NOT NULL,
    unidad_medida VARCHAR(30),
    precio_unitario NUMERIC(10,2) NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL,
    observaciones VARCHAR(200),
    CONSTRAINT fk_det_compra FOREIGN KEY (id_compra) REFERENCES compras_proveedores(id_compra),
    CONSTRAINT chk_det_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_det_precio CHECK (precio_unitario >= 0),
    CONSTRAINT chk_det_subtotal CHECK (subtotal >= 0)
);

CREATE TABLE inventario_activos (
    id_activo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra INTEGER NOT NULL,
    tipo_activo VARCHAR(30) CHECK (tipo_activo IN ('ARMA', 'VEHICULO', 'UNIFORME', 'EQUIPO_PROTECCION')),
    descripcion VARCHAR(100) NOT NULL,
    numero_serie_o_placa VARCHAR(50) UNIQUE,
    estado_activo VARCHAR(20) DEFAULT 'DISPONIBLE' CHECK (estado_activo IN ('DISPONIBLE', 'ASIGNADO', 'MANTENIMIENTO')),
    fecha_registro DATE DEFAULT CURRENT_DATE,
    observaciones VARCHAR(200),
    codigo_inventario VARCHAR(50),
    valor_adquisicion NUMERIC(12,2),
    ubicacion_actual VARCHAR(150),
    fecha_adquisicion DATE,
    fecha_baja DATE,
    motivo_baja VARCHAR(300),
    responsable_actual INTEGER,
    CONSTRAINT fk_inv_com FOREIGN KEY (id_compra) REFERENCES compras_proveedores(id_compra),
    CONSTRAINT fk_inv_responsable FOREIGN KEY (responsable_actual) REFERENCES empleados(id_empleado),
    CONSTRAINT uq_inv_codigo UNIQUE (codigo_inventario)
);

CREATE TABLE inventario_materiales (
    id_material INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra INTEGER NOT NULL,
    descripcion VARCHAR(100) NOT NULL,
    cantidad_adquirida NUMERIC(10,2),
    unidad_medida VARCHAR(20),
    stock_actual NUMERIC(10,2) DEFAULT 0,
    fecha_registro DATE DEFAULT CURRENT_DATE,
    observaciones VARCHAR(200),
    CONSTRAINT fk_mat_com FOREIGN KEY (id_compra) REFERENCES compras_proveedores(id_compra)
);

CREATE TABLE asignacion_equipos (
    id_asignacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INTEGER NOT NULL,
    id_activo INTEGER NOT NULL,
    fecha_entrega DATE DEFAULT CURRENT_DATE,
    fecha_devolucion DATE,
    kilometraje_inicial NUMERIC(10,2),
    acta_resguardo_firmada CHAR(1) DEFAULT 'S' CHECK (acta_resguardo_firmada IN ('S', 'N')),
    observaciones VARCHAR(200),
    fecha_hora_entrega TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_hora_devolucion TIMESTAMP,
    kilometraje_final NUMERIC(10,2),
    estado_entrega VARCHAR(30) DEFAULT 'BUENO',
    estado_devolucion VARCHAR(30),
    id_empleado_entrega INTEGER,
    id_empleado_recibe INTEGER,
    id_usuario_asigna INTEGER,
    CONSTRAINT fk_ase_emp FOREIGN KEY (id_empleado) REFERENCES empleados(id_empleado),
    CONSTRAINT fk_ase_act FOREIGN KEY (id_activo) REFERENCES inventario_activos(id_activo),
    CONSTRAINT fk_ase_emp_entrega FOREIGN KEY (id_empleado_entrega) REFERENCES empleados(id_empleado),
    CONSTRAINT fk_ase_emp_recibe FOREIGN KEY (id_empleado_recibe) REFERENCES empleados(id_empleado),
    CONSTRAINT fk_ase_usuario FOREIGN KEY (id_usuario_asigna) REFERENCES usuarios(id_usuario),
    CONSTRAINT chk_ase_estado_entrega CHECK (estado_entrega IN ('BUENO', 'REGULAR', 'DANADO')),
    CONSTRAINT chk_ase_estado_devolucion CHECK (estado_devolucion IN ('BUENO', 'REGULAR', 'DANADO', 'INCOMPLETO', 'PERDIDO')),
    CONSTRAINT chk_ase_fechas CHECK (fecha_devolucion IS NULL OR fecha_devolucion >= fecha_entrega),
    CONSTRAINT chk_ase_kilometraje CHECK (kilometraje_final IS NULL OR kilometraje_final >= kilometraje_inicial)
);

CREATE TABLE armas (
    id_arma INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_activo INTEGER NOT NULL,
    marca VARCHAR(50) NOT NULL,
    modelo VARCHAR(50),
    calibre VARCHAR(30),
    tipo_arma VARCHAR(50) NOT NULL,
    numero_registro VARCHAR(50),
    numero_serie VARCHAR(50),
    fecha_adquisicion DATE,
    fecha_inspeccion DATE,
    estado_arma VARCHAR(30) DEFAULT 'OPERATIVA' CHECK (estado_arma IN ('OPERATIVA', 'MANTENIMIENTO', 'FUERA_SERVICIO', 'BAJA')),
    observaciones VARCHAR(300),
    CONSTRAINT fk_arma_activo FOREIGN KEY (id_activo) REFERENCES inventario_activos(id_activo),
    CONSTRAINT uq_arma_activo UNIQUE (id_activo),
    CONSTRAINT uq_arma_serie UNIQUE (numero_serie)
);

CREATE TABLE vehiculos (
    id_vehiculo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_activo INTEGER NOT NULL,
    tipo_vehiculo VARCHAR(30) NOT NULL CHECK (tipo_vehiculo IN ('AUTOMOVIL', 'CAMIONETA', 'MOTOCICLETA', 'CAMION', 'OTRO')),
    marca VARCHAR(50) NOT NULL,
    modelo VARCHAR(50),
    anio SMALLINT,
    color VARCHAR(30),
    placa VARCHAR(20) UNIQUE,
    vin VARCHAR(50) UNIQUE,
    numero_motor VARCHAR(50) UNIQUE,
    kilometraje_actual NUMERIC(12,2) DEFAULT 0,
    fecha_adquisicion DATE,
    fecha_vencimiento_matricula DATE,
    estado_vehiculo VARCHAR(30) DEFAULT 'DISPONIBLE' CHECK (estado_vehiculo IN ('DISPONIBLE', 'ASIGNADO', 'MANTENIMIENTO', 'FUERA_SERVICIO', 'BAJA')),
    observaciones VARCHAR(300),
    CONSTRAINT fk_veh_activo FOREIGN KEY (id_activo) REFERENCES inventario_activos(id_activo),
    CONSTRAINT uq_veh_activo UNIQUE (id_activo)
);

CREATE TABLE uniformes (
    id_uniforme INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_activo INTEGER NOT NULL,
    tipo_prenda VARCHAR(50) NOT NULL,
    talla VARCHAR(20),
    genero VARCHAR(20),
    cantidad NUMERIC(10,2) DEFAULT 1,
    estado_uniforme VARCHAR(30) DEFAULT 'DISPONIBLE' CHECK (estado_uniforme IN ('DISPONIBLE', 'ASIGNADO', 'DANADO', 'PERDIDO', 'BAJA')),
    observaciones VARCHAR(300),
    CONSTRAINT fk_uni_activo FOREIGN KEY (id_activo) REFERENCES inventario_activos(id_activo),
    CONSTRAINT uq_uni_activo UNIQUE (id_activo)
);

CREATE TABLE asignacion_uniformes (
    id_asignacion_uniforme INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INTEGER NOT NULL,
    id_uniforme INTEGER NOT NULL,
    cantidad NUMERIC(10,2) DEFAULT 1 NOT NULL,
    fecha_entrega DATE DEFAULT CURRENT_DATE NOT NULL,
    fecha_devolucion DATE,
    estado_asignacion VARCHAR(30) DEFAULT 'ACTIVA' CHECK (estado_asignacion IN ('ACTIVA', 'DEVUELTA', 'PERDIDA', 'DANADA')),
    observaciones VARCHAR(300),
    id_usuario_asigna INTEGER,
    CONSTRAINT fk_asig_uni_emp FOREIGN KEY (id_empleado) REFERENCES empleados(id_empleado),
    CONSTRAINT fk_asig_uni_uniforme FOREIGN KEY (id_uniforme) REFERENCES uniformes(id_uniforme),
    CONSTRAINT fk_asig_uni_usuario FOREIGN KEY (id_usuario_asigna) REFERENCES usuarios(id_usuario),
    CONSTRAINT chk_asig_uni_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_au_fechas CHECK (fecha_devolucion IS NULL OR fecha_devolucion >= fecha_entrega)
);

CREATE TABLE movimientos_inventario (
    id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_activo INTEGER,
    id_material INTEGER,
    tipo_movimiento VARCHAR(30) NOT NULL CHECK (tipo_movimiento IN ('ENTRADA', 'SALIDA', 'TRANSFERENCIA', 'DEVOLUCION', 'AJUSTE', 'BAJA')),
    cantidad NUMERIC(10,2) DEFAULT 1 NOT NULL,
    fecha_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ubicacion_origen VARCHAR(100),
    ubicacion_destino VARCHAR(100),
    motivo VARCHAR(300),
    id_empleado_responsable INTEGER,
    id_usuario INTEGER,
    observaciones VARCHAR(300),
    CONSTRAINT fk_mov_activo FOREIGN KEY (id_activo) REFERENCES inventario_activos(id_activo),
    CONSTRAINT fk_mov_material FOREIGN KEY (id_material) REFERENCES inventario_materiales(id_material),
    CONSTRAINT fk_mov_empleado FOREIGN KEY (id_empleado_responsable) REFERENCES empleados(id_empleado),
    CONSTRAINT fk_mov_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario),
    CONSTRAINT chk_mov_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_mov_referencia CHECK (
        (id_activo IS NOT NULL AND id_material IS NULL) OR (id_activo IS NULL AND id_material IS NOT NULL)
    )
);

-- ---------- 5. PAGOS ADMINISTRATIVOS ----------
CREATE TABLE pagos_administrativos (
    id_pago_admin INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_permiso INTEGER,
    concepto VARCHAR(100) NOT NULL,
    categoria VARCHAR(50) CHECK (categoria IN ('RAP', 'IHSS', 'CANON', 'ALCALDIA', 'OTRO')),
    fecha_vencimiento DATE NOT NULL,
    fecha_pago DATE,
    monto NUMERIC(10,2) NOT NULL,
    estado VARCHAR(20) DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'PAGADO', 'VENCIDO')),
    observaciones VARCHAR(200),
    CONSTRAINT fk_pad_perm FOREIGN KEY (id_permiso) REFERENCES permisos_administrativos(id_permiso)
);

-- ---------- 6. DOCUMENTOS ADJUNTOS ----------
CREATE TABLE documentos_adjuntos (
    id_documento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla_referencia VARCHAR(50) NOT NULL,
    id_referencia INTEGER NOT NULL,
    nombre_archivo VARCHAR(200) NOT NULL,
    tipo_archivo VARCHAR(50),
    archivo_blob BYTEA,
    fecha_subida DATE DEFAULT CURRENT_DATE,
    id_empleado_subio INTEGER,
    descripcion VARCHAR(200),
    CONSTRAINT fk_doc_emp_sub FOREIGN KEY (id_empleado_subio) REFERENCES empleados(id_empleado)
);

-- ---------- 7. AUDITORIA ----------
CREATE TABLE auditoria (
    id_auditoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    accion VARCHAR(20) NOT NULL CHECK (accion IN ('INSERT', 'UPDATE', 'DELETE', 'LOGIN')),
    tabla_afectada VARCHAR(50),
    id_registro INTEGER,
    fecha_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    datos_anteriores VARCHAR(4000),
    datos_nuevos VARCHAR(4000),
    CONSTRAINT fk_aud_usu FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
);

-- ---------- 8. ALERTAS DE VENCIMIENTO ----------
CREATE TABLE alertas_vencimiento (
    id_alerta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_entidad VARCHAR(50) NOT NULL,
    id_referencia INTEGER NOT NULL,
    descripcion VARCHAR(200),
    fecha_vencimiento DATE NOT NULL,
    dias_anticipacion SMALLINT DEFAULT 30,
    fecha_alerta DATE,
    prioridad VARCHAR(20) DEFAULT 'MEDIA' CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    estado VARCHAR(20) DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'ATENDIDA', 'IGNORADA', 'VENCIDA')),
    fecha_atencion DATE,
    id_usuario_atendio INTEGER,
    observaciones VARCHAR(300),
    CONSTRAINT fk_alerta_usuario FOREIGN KEY (id_usuario_atendio) REFERENCES usuarios(id_usuario),
    CONSTRAINT chk_alerta_dias CHECK (dias_anticipacion >= 0)
);

-- ---------- 9. INDICES ----------
CREATE INDEX idx_asp_empleado ON asignacion_puestos(id_empleado);
CREATE INDEX idx_asp_puesto ON asignacion_puestos(id_puesto);
CREATE INDEX idx_asp_turno ON asignacion_puestos(id_turno);
CREATE INDEX idx_ase_empleado ON asignacion_equipos(id_empleado);
CREATE INDEX idx_ase_activo ON asignacion_equipos(id_activo);
CREATE INDEX idx_mov_activo ON movimientos_inventario(id_activo);
CREATE INDEX idx_mov_material ON movimientos_inventario(id_material);
CREATE INDEX idx_mov_fecha ON movimientos_inventario(fecha_hora);
CREATE INDEX idx_alerta_vencimiento ON alertas_vencimiento(fecha_vencimiento);
CREATE INDEX idx_alerta_estado ON alertas_vencimiento(estado);
CREATE INDEX idx_det_compra ON detalle_compras(id_compra);
